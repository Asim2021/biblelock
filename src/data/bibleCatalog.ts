/**
 * Returns clean human-readable badge acronym (e.g. 'IRV', 'WEB', 'KJV', 'RVR60')
 */
export function getTranslationBadge(code: string): string {
	const found = BIBLE_CATALOG.find((item) => item.code === code);
	if (found && found.shortCode) return found.shortCode;

	if (code.includes('_')) {
		const sub = code.split('_')[1];
		if (sub.startsWith('irv')) return 'IRV';
		return sub.toUpperCase();
	}
	return code.toUpperCase();
}

/**
 * Returns full download URL for a catalog item
 */
export function getCatalogItemDownloadUrl(item: BibleCatalogItem): string {
	if (item.isPreloaded) return '';
	return `${BIBLE_CATALOG_BASE_URL}${item.filename}`;
}
